function pickArchetype(slug, title) {
  if (title === 'อุบลราชธานี' || slug === 'อุบลราชธานี') {
    return ARCHETYPES.find((a) => a.id === 'ubon-storefront');
  }
  // Region hub: force shipping-focused structure, not a province twin
  if (title === 'ภาคอีสาน' || slug === 'ภาคอีสาน') {
    return ARCHETYPES.find((a) => a.id === 'remote-shipping');
  }
  // exclude ubon-only from rotation
  const pool = ARCHETYPES.filter((a) => a.id !== 'ubon-storefront');
  return pool[hash(slug) % pool.length];
}

/** Unique lead index per slug (avoids hash collisions in the opening window). */
const LEAD_INDEX_BY_SLUG = new Map();
function assignLeadIndices(slugs) {
  const sorted = [...slugs].sort((a, b) => a.localeCompare(b, 'th'));
  sorted.forEach((slug, i) => {
    LEAD_INDEX_BY_SLUG.set(slug, i % LEAD_BANK.length);
  });
}

