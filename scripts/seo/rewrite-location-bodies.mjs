function buildBody({ title, slug, region, areas, neighborsHint, arch }) {
  const isUbon = slug === 'อุบลราชธานี' || title === 'อุบลราชธานี';
  const v = hash(slug) % 6;
  const plan = arch.sectionPlan(v);

  const h1 = pick(slug, 'h1', [
    `รับซื้อโน๊ตบุ๊ค${title}`,
    `ขายโน๊ตบุ๊คใน${title} — เริ่มจากประเมินออนไลน์`,
    `${title}: ช่องทางรับซื้อโน๊ตบุ๊คผ่านไลน์ ${LINE}`,
    `บริการรับซื้อโน๊ตบุ๊คสำหรับลูกค้าใน${title}`,
  ]);

  const parts = [`## ${h1}`, '', buildOpening(arch, title, slug, region, areas, isUbon).trim(), ''];

  const used = new Set();
  {
    const storeH2 = isUbon
      ? pick(slug, 'store.h2', ['เข้าตรวจที่หน้าร้าน', 'คิวหน้าร้านและการประเมินล่วงหน้า', 'หน้าร้านจริงในจังหวัดนี้'])
      : pick(slug, 'store.h2', ['ขอบเขตบริการในพื้นที่นี้', 'หน้าร้านอยู่ที่ไหน', 'สาขาหรือแค่พื้นที่บริการ']);
    parts.push(`## ${storeH2}`, '', storefrontNote(title, slug, isUbon), '');
  }
  for (const key of plan) {
    if (used.has(key)) continue;
    used.add(key);
    const fn = SECTIONS[key];
    if (!fn) continue;
    const section =
      key === 'areaRef'
        ? fn(title, slug, areas)
        : key === 'processSteps'
          ? fn(title, slug, isUbon)
          : fn(title, slug);
    if (!section) continue;
    parts.push(`## ${section.h2}`, '', section.body.trim(), '');
  }

  // Light unique bridge using areas (not a long SEO district list)
  if (!used.has('areaRef') && areas.length) {
    parts.push(
      `## หมายเหตุโซนสั้น ๆ`,
      '',
      areaMention(title, areas, slug, 'bridge.area'),
      '',
    );
  }

  if (neighborsHint) {
    parts.push(
      `## พื้นที่ใกล้เคียง`,
      '',
      neighborsHint,
      '',
    );
  }

  // Optional tiny related links block — wording varies; omit sometimes for diversity
  if (hash(`${slug}::links`) % 3 !== 0) {
    const linkBlock = pick(slug, 'links', [
      `อ่านเพิ่ม: [หน้าแรก](/) · [มือสอง](/รับซื้อโน๊ตบุ๊คมือสอง/) · [พื้นที่ให้บริการ](/พื้นที่ให้บริการ/)`,
      `ลิงก์ที่เกี่ยวข้อง: [ตีราคาโน๊ตบุ๊ค](/ตีราคาโน๊ตบุ๊ค/) · [เครื่องเสีย](/รับซื้อโน๊ตบุ๊ค/เครื่องเสีย/)`,
      `ดูเงื่อนไขอาการที่พบบ่อย: [จอแตก](/รับซื้อโน๊ตบุ๊ค/จอแตก/) · [เปิดไม่ติด](/รับซื้อโน๊ตบุ๊ค/เปิดไม่ติด/) · [แบตเสื่อม](/รับซื้อโน๊ตบุ๊ค/แบตเสื่อม/)`,
    ]);
    parts.push(linkBlock, '');
  }

  const closing = pick(slug, 'closing', arch.closings(title));
  parts.push('---', '', closing, '');

  return parts.join('\n').replace(/\n{3,}/g, '\n\n');
}

