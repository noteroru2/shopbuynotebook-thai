function neighborFromBody(oldBody) {
  const m = oldBody.match(/## (?:จังหวัดใกล้เคียง|พื้นที่ใกล้เคียง)[\s\S]*?\n\n([^\n#]+)/);
  if (!m) return '';
  const line = m[1].trim();
  if (line.includes('](/รับซื้อโน๊ตบุ๊ค/')) return line;
  return '';
}

