function hash(s) {
  let h = 0;
  for (let i = 0; i < s.length; i++) h = (Math.imul(31, h) + s.charCodeAt(i)) | 0;
  return Math.abs(h);
}

function pick(slug, key, arr) {
  if (!arr.length) return '';
  return arr[hash(`${slug}::${key}`) % arr.length];
}

function splitFm(raw) {
  if (!raw.startsWith('---')) return { fm: '', body: raw };
  const end = raw.indexOf('\n---', 3);
  if (end === -1) return { fm: '', body: raw };
  return { fm: raw.slice(0, end + 4), body: raw.slice(end + 4) };
}

function getFmField(fm, key) {
  const re = new RegExp(`^${key}:\\s*(.+)$`, 'm');
  const m = fm.match(re);
  return m ? m[1].replace(/^["']|["']$/g, '').trim() : '';
}

function getList(fm, key) {
  const re = new RegExp(`^${key}:\\r?\\n((?:[ \\t]*- .+\\r?\\n?)+)`, 'm');
  const m = fm.match(re);
  if (!m) return [];
  return m[1]
    .split(/\r?\n/)
    .map((l) => l.replace(/^\s*-\s*/, '').trim())
    .filter(Boolean);
}

function yamlFaqs(faqs) {
  return faqs
    .map((f) => `- question: ${f.q}\n  answer: ${wrapYaml(f.a)}`)
    .join('\n');
}

function wrapYaml(s) {
  if (/[:#{}[\],&*?|>!<%@`]/.test(s) || s.includes('\n')) {
    return `"${s.replace(/"/g, '\\"')}"`;
  }
  return s;
}

/** Remove every faqs: block (including wrapped answer lines), then insert one clean block. */
function replaceFaqs(fm, faqsYaml) {
  let out = fm.replace(/^faqs:\r?\n(?:[ \t]*- .+\r?\n|[ \t]{2,}.+\r?\n)*/gm, '');
  out = out.replace(/\n{3,}/g, '\n\n');
  if (!/\n---\s*$/.test(out)) return `${out.trimEnd()}\nfaqs:\n${faqsYaml}\n---\n`;
  return out.replace(/\n---\s*$/, `\nfaqs:\n${faqsYaml}\n---`);
}

function setSubAreas(fm, areas) {
  const kept = areas.slice(0, 5);
  const block = kept.map((a) => `- ${a}`).join('\n');
  if (/^subAreas:\r?\n(?:[ \t]*- .+\r?\n?)+/m.test(fm)) {
    return fm.replace(/^subAreas:\r?\n(?:[ \t]*- .+\r?\n?)+/m, `subAreas:\n${block}\n`);
  }
  return fm;
}

